import type { FlowRow } from '../features/flowlist/types';

export type Value = string | number;
/** A record in a generic collection. `_id` is unique within its collection. */
export type Row = Record<string, Value> & { _id: number };

export const RECORD_COLLECTIONS = [
  'clientes', 'proveedores', 'productos', 'categorias', 'almacenes', 'usuarios', 'roles',
  'conductores', 'vehiculos', 'preciosProv', 'stock', 'kardex', 'transferencias', 'ajustes', 'caja', 'bancos', 'comprobantes', 'cxc', 'cxp',
] as const;
export type RecordCollection = (typeof RECORD_COLLECTIONS)[number];

export interface OrderLine {
  sku: string;
  name: string;
  unit: string;
  qty: number;
  /** Unit price (sales) or unit cost (purchases), before IGV. */
  price: number;
}

export interface OrderParty {
  code?: string;
  name: string;
  ruc: string;
  contact: string;
  terms: string;
  address: string;
  email?: string;
}

/** A sales or purchase order and the state of its 5-step flow. */
export interface Order {
  kind: 'venta' | 'compra';
  code: string;
  /** ISO date-time of creation. */
  createdAt: string;
  party: OrderParty;
  lines: OrderLine[];
  warehouse: string;
  /** Number of completed steps (1–5). */
  done: number;
  /** Values entered in each step's form, by step index. */
  forms: Record<number, Record<string, string>>;
  /** Document generated by each completed step. */
  docs: Record<number, string>;
  /** Who completed each step and when (ISO). */
  log: Record<number, { who: string; at: string }>;
  /** Quotation / purchase request it came from. */
  origin?: string;
  seller: string;
  igvRate: number;
  cancelled?: boolean;
}

export interface DocFile {
  id: number;
  name: string;
  cat: string;
  ref: string;
  entity: string;
  size: string;
  /** ISO date. */
  date: string;
  by: string;
  version: string;
  /** Uploaded file stored in IndexedDB under this key. */
  blobKey?: string;
  /** System-generated document: printable HTML. */
  html?: string;
}

export interface AuditEvent {
  id: string;
  /** ISO date-time. */
  at: string;
  user: string;
  role: string;
  action: 'Ingreso' | 'Crear' | 'Editar' | 'Eliminar' | 'Exportar' | 'Descargar';
  module: string;
  ref: string;
  desc: string;
  result: 'Exitoso' | 'Fallido' | 'Denegado';
  changes: [field: string, before: string, after: string][];
  note: string;
  ip: string;
  device: string;
}

/** role → module → [ver, crear, editar, eliminar, aprobar] */
export type PermMatrix = Record<string, Record<string, boolean[]>>;

export type Settings = Record<string, string | boolean>;

export interface DB {
  version: 1;
  records: Record<RecordCollection, Row[]>;
  cotizaciones: FlowRow[];
  solicitudes: FlowRow[];
  orders: Order[];
  documentos: DocFile[];
  audit: AuditEvent[];
  permisos: PermMatrix;
  settings: Settings;
  /** Last number used per code prefix (e.g. "OV-2026-"). */
  counters: Record<string, number>;
  /** Keys of alerts the user marked as read. */
  alertsRead: string[];
  reportSchedules: { report: string; email: string; freq: string }[];
}